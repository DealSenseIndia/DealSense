/**
 * Smart Setups — space blueprints.
 *
 * A blueprint is the *structure* of a room, never a product list. It says which
 * functional slots a space needs, what share of the budget each deserves, and
 * what a buyer already owns. The setup engine fills every slot at request time
 * from listings DealSense genuinely tracks and prices, then judges each item
 * with the same verdict used on product pages.
 *
 * No price, title, ASIN or image lives here. Anything the catalogue cannot
 * verify is reported as a gap rather than filled with an invented product.
 */

